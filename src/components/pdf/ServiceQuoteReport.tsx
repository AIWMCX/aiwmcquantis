/**
 * Client-side PDF for a Service Job quote.
 * Uses the project-canonical @react-pdf/renderer pipeline.
 */
import { Document, Page, StyleSheet, Text, View } from '@react-pdf/renderer';
import type { ServiceJob } from '@/lib/service-job/types';

const styles = StyleSheet.create({
  page: { padding: 36, fontSize: 11, fontFamily: 'Helvetica', color: '#111' },
  h1: { fontSize: 22, fontWeight: 700, marginBottom: 6 },
  h2: { fontSize: 13, fontWeight: 700, marginTop: 16, marginBottom: 6 },
  muted: { color: '#666' },
  row: { flexDirection: 'row', justifyContent: 'space-between', marginBottom: 4 },
  bandRow: { flexDirection: 'row', gap: 8, marginTop: 8 },
  band: { flex: 1, padding: 10, borderWidth: 1, borderColor: '#ddd', borderRadius: 4 },
  bandTitle: { fontSize: 9, color: '#666', textTransform: 'uppercase' },
  bandPrice: { fontSize: 18, fontWeight: 700, marginTop: 2 },
  table: { borderTopWidth: 1, borderColor: '#eee', marginTop: 4 },
  trh: { flexDirection: 'row', backgroundColor: '#f6f6f6', padding: 6 },
  tr: { flexDirection: 'row', padding: 6, borderBottomWidth: 1, borderBottomColor: '#eee' },
  th: { fontSize: 9, fontWeight: 700, color: '#444' },
  td: { fontSize: 10 },
  footer: { position: 'absolute', bottom: 24, left: 36, right: 36, fontSize: 8, color: '#888', textAlign: 'center' },
  riskRow: { padding: 6, borderLeftWidth: 3, borderLeftColor: '#ccc', backgroundColor: '#fafafa', marginBottom: 4 },
});

function fmt(n: number) {
  return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD', maximumFractionDigits: 0 }).format(n);
}

export function ServiceQuoteReport({ job }: { job: ServiceJob }) {
  const q = job.quote_result;
  return (
    <Document>
      <Page size="LETTER" style={styles.page}>
        <Text style={styles.h1}>Service Quote</Text>
        <Text style={styles.muted}>
          {job.client_name ?? 'Client'} — {new Date(job.created_at).toLocaleDateString()}
        </Text>

        <Text style={styles.h2}>Job details</Text>
        <View style={styles.row}><Text>Trade</Text><Text>{job.trade_id}</Text></View>
        {job.site_address && (
          <View style={styles.row}><Text>Address</Text><Text>{job.site_address}</Text></View>
        )}
        {job.building_type && (
          <View style={styles.row}><Text>Building</Text><Text>{job.building_type}{job.year_built ? ` (${job.year_built})` : ''}</Text></View>
        )}

        {q ? (
          <>
            <Text style={styles.h2}>Price options</Text>
            <View style={styles.bandRow}>
              {(['aggressive', 'balanced', 'defensive'] as const).map((k) => (
                <View key={k} style={styles.band}>
                  <Text style={styles.bandTitle}>{k}</Text>
                  <Text style={styles.bandPrice}>{fmt(q.price_bands[k].price)}</Text>
                  <Text style={styles.muted}>{(q.price_bands[k].margin_pct * 100).toFixed(0)}% margin</Text>
                </View>
              ))}
            </View>

            <Text style={styles.h2}>Scope ({(job.scope_items ?? []).length} items)</Text>
            <View style={styles.table}>
              <View style={styles.trh}>
                <Text style={[styles.th, { flex: 4 }]}>Assembly</Text>
                <Text style={[styles.th, { flex: 1, textAlign: 'right' }]}>Qty</Text>
                <Text style={[styles.th, { flex: 1, textAlign: 'right' }]}>Difficulty</Text>
              </View>
              {(job.scope_items ?? []).map((s, i) => (
                <View key={i} style={styles.tr}>
                  <Text style={[styles.td, { flex: 4 }]}>{s.assembly_id.slice(0, 8)}…</Text>
                  <Text style={[styles.td, { flex: 1, textAlign: 'right' }]}>{s.quantity}</Text>
                  <Text style={[styles.td, { flex: 1, textAlign: 'right' }]}>{s.difficulty_factor.toFixed(2)}×</Text>
                </View>
              ))}
            </View>

            {q.risks.length > 0 && (
              <>
                <Text style={styles.h2}>Risk notes</Text>
                {q.risks.slice(0, 5).map((r) => (
                  <View key={r.code} style={styles.riskRow}>
                    <Text style={{ fontSize: 9, color: '#666', textTransform: 'uppercase' }}>
                      {r.severity} · {r.category}
                    </Text>
                    <Text>{r.message}</Text>
                  </View>
                ))}
              </>
            )}
          </>
        ) : (
          <Text style={styles.muted}>Quote not yet computed.</Text>
        )}

        <Text style={styles.footer}>
          Generated by AIWMC Quantis — Service Job Quoting. Pricing is an estimate based on supplied scope and assumptions.
        </Text>
      </Page>
    </Document>
  );
}
